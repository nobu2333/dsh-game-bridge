"""Coverage metrics for the v3 GamePack matrix.

The point of v3 is breadth, but a hand-authored pack must not be counted the
same way as a pack generated by the automatic probe. This module computes:

- coverage@T1 / coverage@T2 from the matrix;
- T1 split by pack origin (auto / assisted / human);
- explicit interventions total;
- packs missing evidence;
- strict-T2 eligibility from duration/actions/restarts.

No game names or engine branches; matrix and packs are data.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def _read_json(path: str | Path) -> dict:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    return payload if isinstance(payload, dict) else {}


def load_pack_origins(pack_paths: list[str | Path]) -> tuple[dict[str, dict], list[str]]:
    origins: dict[str, dict] = {}
    errors: list[str] = []
    for raw in pack_paths:
        path = Path(raw)
        try:
            pack = _read_json(path)
        except Exception as error:  # noqa: BLE001
            errors.append(f"{path}: {error}")
            continue
        pack_id = str(pack.get("id") or "")
        if not pack_id:
            errors.append(f"{path}: missing id")
            continue
        origins[pack_id] = {
            "origin": str(pack.get("origin") or "human"),
            "interventions": int(pack.get("interventions") or 0),
            "evidence": list(pack.get("evidence") or []),
            "path": str(path),
        }
        origins[str(path)] = origins[pack_id]
        try:
            origins[str(path.resolve())] = origins[pack_id]
        except OSError:
            pass
    return origins, errors


def summarize_coverage(
    matrix: dict,
    origins: dict[str, dict],
) -> dict:
    games = matrix.get("games") if isinstance(matrix.get("games"), list) else []
    t1_total = 0
    t1_auto = 0
    t1_assisted = 0
    t1_human = 0
    t2_total = 0
    interventions = 0
    missing_evidence: list[str] = []
    strict_t2: list[str] = []
    for game in games:
        if not isinstance(game, dict):
            continue
        game_id = str(game.get("id") or "")
        status = str(game.get("status") or "")
        pack_id = str(game.get("pack_id") or game.get("pack") or "")
        meta = origins.get(pack_id) or origins.get(str(game.get("pack") or "")) or {}
        try:
            meta = meta or origins.get(str(Path(str(game.get("pack") or "")).resolve()))
        except OSError:
            pass
        # T2 requires T1, so a t2_pass game also satisfies T1 coverage.
        t1_satisfied = status.startswith("t1") or status.startswith("t2")
        if t1_satisfied and status.endswith("pass"):
            t1_total += 1
            origin = str(meta.get("origin") or "human")
            if origin == "auto":
                t1_auto += 1
            elif origin == "assisted":
                t1_assisted += 1
            else:
                t1_human += 1
            interventions += int(meta.get("interventions") or 0)
            if not meta.get("evidence"):
                missing_evidence.append(game_id)
        if status in ("t2_pass", "t2") or status.startswith("t2_pass"):
            t2_total += 1
            strict = game.get("strict_t2")
            if isinstance(strict, dict) and strict.get("valid"):
                strict_t2.append(game_id)
    return {
        "t1_total": t1_total,
        "t1_auto": t1_auto,
        "t1_assisted": t1_assisted,
        "t1_human": t1_human,
        "t2_total": t2_total,
        "strict_t2": strict_t2,
        "interventions": interventions,
        "missing_evidence": missing_evidence,
        "target_met": t1_total >= 3 and t2_total >= 2,
        "auto_target_met": t1_auto >= 1,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Summarize v3 GamePack coverage.")
    parser.add_argument("--matrix", required=True)
    parser.add_argument("--packs", nargs="*", default=[])
    args = parser.parse_args(argv)
    origins, errors = load_pack_origins(args.packs)
    result = summarize_coverage(_read_json(args.matrix), origins)
    result["pack_errors"] = errors
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
